"""Generate Route-B labels for IEEE 39-bus without overwriting v1 data.

The output keeps the same sample schema used by train_gat39_v1.py and
train_rl39_v1.py, but the metadata records strict Route-B audit fields.
Labels are still active-power dispatches from the linear N-1 SCED generator;
strict AC-PF is only audited, not used as the supervised target.
"""
import argparse
import json
import sys
from pathlib import Path


ROOT = Path(r".")
sys.path.insert(0, str(ROOT))

import generate_case39_gt_v1 as gen39
from case39_route_b_utils import CASE39_VMIN, CASE39_VMAX


def parse_levels(text):
    return [float(x.strip()) for x in text.split(",") if x.strip()]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--demand-levels", default="5.6,5.8,6.0,6.1,6.2")
    parser.add_argument("--samples-per-level", type=int, default=40)
    parser.add_argument("--vmin", type=float, default=CASE39_VMIN)
    parser.add_argument("--vmax", type=float, default=CASE39_VMAX)
    parser.add_argument("--fl-scale", type=float, default=1.0)
    parser.add_argument("--output", default="case39_routeb_dataset.json")
    args = parser.parse_args()

    gen39.OUTPUT = args.output
    gen39.DEMAND_GW = parse_levels(args.demand_levels)
    gen39.N_PER = args.samples_per_level
    gen39.VMIN = args.vmin
    gen39.VMAX = args.vmax
    gen39.FL_SCALE = args.fl_scale

    gen39.main()

    out_path = ROOT / args.output
    with open(out_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    data["route_b_config"] = {
        "source": "generate_case39_route_b_labels.py",
        "demand_levels_gw": gen39.DEMAND_GW,
        "samples_per_level": args.samples_per_level,
        "vmin": args.vmin,
        "vmax": args.vmax,
        "fl_scale": args.fl_scale,
        "note": "Active-power labels are generated by the linear N-1 SCED pipeline; strict AC-PF is audited separately.",
    }
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
    print(f"Route-B case39 dataset ready: {out_path}")


if __name__ == "__main__":
    main()
